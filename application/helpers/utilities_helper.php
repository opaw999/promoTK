    public static function getCategory($input) {

        $category = self::sanitizeInput($input);
        switch ($category) {
            case "1": 
                return "Rank & File";
            case "2": 
                return "Supervisory";
            case "3": 
                return "Managerial";
            default: 
                return "";
        }
    }

