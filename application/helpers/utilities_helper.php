    public static function generateTableHeader($columns) {

        $header = '<table border=1>';
        $header .= '<tr class="text-center">';
    
        // Iterate through each column and add it to the header row
        foreach ($columns as $column) {
            $header .= "<th> $column </th>";
        }
    
        $header .= '</tr>';
            
        echo $header;
    }

