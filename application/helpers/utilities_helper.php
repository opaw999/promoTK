    public static function getLocation($code){

        $ec	 	= explode(".",$code);
        $cc	   	= @$ec[0];
        $bc		= @$ec[1];
        $dc		= @$ec[2];
        $sc		= @$ec[3];
        $ssc	= @$ec[4];	
               
        if($ssc  != "")
            $location = "(company_code = '$cc' and bunit_code = '$bc' and dept_code = '$dc' and section_code = '$sc' and sub_section_code = '$ssc')"; 
        else if($sc  != "") 	
            $location = "(company_code = '$cc' and bunit_code = '$bc' and dept_code = '$dc' and section_code = '$sc')"; 
        else if($dc != ""){
            $location = "(company_code = '$cc' and bunit_code = '$bc' and dept_code = '$dc')";
        }
        else if($bc != "")
            $location = "(company_code = '$cc' and bunit_code = '$bc')"; 
        else
            $location = "(company_code = '$cc')"; 

        return $location;        
    }
